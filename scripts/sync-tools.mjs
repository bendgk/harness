#!/usr/bin/env node
/**
 * Regenerates the "Tools" section of CLAUDE.md from the tool registry, so the
 * docs every agent reads can never drift from what the MCP server serves.
 *
 *   node scripts/sync-tools.mjs          rewrite CLAUDE.md
 *   node scripts/sync-tools.mjs --check  exit 1 if CLAUDE.md is stale
 *
 * The registry is bundled with esbuild and loaded in plain Node; tool modules
 * import only zod and types, which is what makes that possible.
 */
import { build } from 'esbuild'
import { createRequire } from 'node:module'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outfile = join(root, 'node_modules/.cache/paper/tools.cjs')
const docPath = join(root, 'CLAUDE.md')
const BEGIN = '<!-- tools:begin (generated by `npm run tools:sync`; do not edit by hand) -->'
const END = '<!-- tools:end -->'

mkdirSync(dirname(outfile), { recursive: true })
await build({
  entryPoints: [join(root, 'src/main/tools/index.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  packages: 'external',
  logLevel: 'silent',
  plugins: [{
    name: 'alias',
    setup(b) {
      b.onResolve({ filter: /^@shared\// }, (a) => ({ path: join(root, 'src/shared', a.path.slice(8)) + '.ts' }))
    }
  }]
})

const require = createRequire(import.meta.url)
const { z } = require('zod')
const { TOOLS } = require(outfile)

const GROUPS = {
  app: ['Instance', 'Identify the instance and reach every tool.'],
  sessions: ['Sessions', 'The PTY sessions Paper runs: agents and shells.'],
  ui: ['Renderer', 'What is on screen, and driving it.'],
  dev: ['Hot reload & logs', 'Live code loading and diagnostics.'],
  state: ['Persisted state', 'What survives a restart.'],
  machines: ['Machines', 'Remote computers (ssh host aliases) agents may work on or move to.']
}

function typeOf(prop) {
  if (prop.enum) return prop.enum.map((v) => JSON.stringify(v)).join(' \\| ')
  if (prop.anyOf) return prop.anyOf.map(typeOf).join(' \\| ')
  if (prop.type === 'array') return `${typeOf(prop.items ?? {})}[]`
  return prop.type ?? 'any'
}

function renderTool(t) {
  const schema = z.toJSONSchema(z.object(t.input))
  const props = schema.properties ?? {}
  const required = new Set(schema.required ?? [])
  const lines = [`#### \`${t.name}\`${t.mutates ? '' : ' · read-only'}`, '', t.description, '']
  const keys = Object.keys(props)
  if (keys.length) {
    lines.push('| param | type | | description |', '|---|---|---|---|')
    for (const k of keys) {
      const p = props[k]
      const dflt = p.default !== undefined ? `default \`${JSON.stringify(p.default)}\`` : required.has(k) ? 'required' : 'optional'
      lines.push(`| \`${k}\` | ${typeOf(p)} | ${dflt} | ${(p.description ?? '').replace(/\|/g, '\\|')} |`)
    }
  } else {
    lines.push('_No parameters._')
  }
  lines.push('')
  return lines.join('\n')
}

const sections = []
for (const [group, [title, blurb]] of Object.entries(GROUPS)) {
  const tools = TOOLS.filter((t) => t.group === group)
  if (!tools.length) continue
  sections.push(`### ${title}`, '', blurb, '', ...tools.map(renderTool))
}
const unknown = TOOLS.filter((t) => !GROUPS[t.group])
if (unknown.length) sections.push('### Other', '', ...unknown.map(renderTool))

const generated = [
  BEGIN,
  '',
  `${TOOLS.length} tools, served as \`mcp__paper__<name>\`. Read-only tools are marked; the rest change state.`,
  '',
  ...sections,
  END
].join('\n')

if (!existsSync(docPath)) {
  console.error('CLAUDE.md is missing; create it with the tool markers first.')
  process.exit(1)
}
const doc = readFileSync(docPath, 'utf8')
const start = doc.indexOf(BEGIN)
const end = doc.indexOf(END)
if (start < 0 || end < 0) {
  console.error(`CLAUDE.md must contain the markers:\n${BEGIN}\n${END}`)
  process.exit(1)
}
const next = doc.slice(0, start) + generated + doc.slice(end + END.length)

if (process.argv.includes('--check')) {
  if (next !== doc) {
    console.error('CLAUDE.md tool section is stale. Run: npm run tools:sync')
    process.exit(1)
  }
  console.log(`CLAUDE.md tools in sync (${TOOLS.length} tools).`)
} else {
  writeFileSync(docPath, next)
  console.log(`CLAUDE.md updated (${TOOLS.length} tools).`)
}
